export function getDemoScholarships(country?: string, degreeLevel?: string, fieldOfStudy?: string): any[] {
  let results = [...DEMO_SCHOLARSHIPS];

  if (country && country !== "all") {
    results = results.filter(s => s.country.toLowerCase().includes(country.toLowerCase()));
  }
  if (degreeLevel && degreeLevel !== "all") {
    results = results.filter(s => s.degree_level.toLowerCase() === degreeLevel.toLowerCase());
  }
  if (fieldOfStudy && fieldOfStudy !== "all") {
    results = results.filter(s =>
      s.field_of_study === "All Fields" ||
      s.field_of_study?.toLowerCase().includes(fieldOfStudy.toLowerCase())
    );
  }

  return results.sort((a, b) => (b.match_score || 0) - (a.match_score || 0));
}
